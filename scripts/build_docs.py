#!/usr/bin/env python3
"""Build the task-guide browser bundle from the reviewed release specifications."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    guides = json.loads((ROOT / 'data/task_guides.json').read_text())
    registry = json.loads((ROOT / 'data/tasks.json').read_text())
    keys = [task['key'] for task in registry['tasks']]
    assert set(keys) == set(guides['tasks']), 'Task-guide coverage differs from the task registry'
    tasks = {}
    for key in keys:
        guide = guides['tasks'][key]
        assert all(guide.get(field) for field in ('task_id', 'directory', 'objective', 'workspace', 'requirements', 'workflow', 'evaluation', 'sources')), key
        assert guide['directory'].startswith('tasks/latest/') and '..' not in guide['directory'], key
        tasks[key] = {field: value for field, value in guide.items() if field != 'sources'}
    return '/* Generated by scripts/build_docs.py. */\nwindow.INFRATHON_DOCS=' + json.dumps({'tasks': tasks}, ensure_ascii=False, separators=(',', ':')) + ';\n'


if __name__ == '__main__':
    (ROOT / 'site/data/docs.js').write_text(build())
    print('Built guides for all 25 tasks.')
